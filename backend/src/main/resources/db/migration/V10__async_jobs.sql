CREATE TABLE document_async_job (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    document_id BIGINT NOT NULL,
    document_version_id BIGINT NOT NULL,
    task_type VARCHAR(16) NOT NULL,
    task_key VARCHAR(100) NOT NULL UNIQUE,
    payload_json JSON NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempts INT NOT NULL DEFAULT 0,
    error_code VARCHAR(64) NULL,
    message_token CHAR(36) NOT NULL,
    run_token CHAR(36) NULL,
    lease_until DATETIME(6) NULL,
    next_attempt_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    dispatched_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_async_document FOREIGN KEY(document_id) REFERENCES document(id),
    CONSTRAINT fk_async_version FOREIGN KEY(document_version_id) REFERENCES document_version(id),
    CONSTRAINT ck_async_type CHECK(task_type IN ('PARSE','INDEX')),
    CONSTRAINT ck_async_status CHECK(status IN ('PENDING','PROCESSING','SUCCEEDED','FAILED')),
    CONSTRAINT ck_async_attempts CHECK(attempts BETWEEN 0 AND 5),
    INDEX ix_async_dispatch(status,next_attempt_at,dispatched_at),
    INDEX ix_async_lease(status,lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
