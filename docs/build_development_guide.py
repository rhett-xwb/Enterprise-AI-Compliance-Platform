def table(headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.autofit = False
    for cell, text, width in zip(t.rows[0].cells, headers, widths):
        cell.text = text
        cell.width = Cm(width)
    for row in rows:
        cells = t.add_row().cells
        for c, text, width in zip(cells, row, widths):
            c.text = text
            c.width = Cm(width)
    for i, row in enumerate(t.rows):
        for cell in row.cells:
            cell.vertical_alignment = 1
            pr = cell._tc.get_or_add_tcPr()
            borders = OxmlElement('w:tcBorders')
            for edge in ['top','left','bottom','right']:
                e = OxmlElement('w:' + edge)
                for k, v in [('val','single'),('sz','4'),('color','D9D9D9')]: e.set(qn('w:'+k),v)
                borders.append(e)
            pr.append(borders)
            margins = OxmlElement('w:tcMar')
            for edge in ['top','left','bottom','right']:
                e = OxmlElement('w:'+edge); e.set(qn('w:w'),'100'); e.set(qn('w:type'),'dxa'); margins.append(e)
            pr.append(margins)
            if i == 0:
                fill = OxmlElement('w:shd'); fill.set(qn('w:fill'),'E7EDF3'); pr.append(fill)
            for para in cell.paragraphs:
                para.paragraph_format.space_after = Pt(2)
                for r in para.runs:
                    r.font.size = Pt(9.5)
                    r.bold = i == 0
        if i == 0:
            repeat = OxmlElement('w:tblHeader'); row._tr.get_or_add_trPr().append(repeat)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)

